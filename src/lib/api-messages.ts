const PREFIXES: [string, string][] = [
  ["Transaction type category must be", "Seçilen işlem türü bu işlem için uygun değil."],
  ["metadataJson", "İşlem türünün ayarları eksik. Türü Ayarlar'dan yeniden kaydedin."],
  ["Invalid status transition", "Kayıt bu duruma doğrudan geçirilemez."],
  ["Invalid value for", "Girilen değerlerden biri geçersiz."],
  ["Malformed JSON", "İstek okunamadı. Sayfayı yenileyip tekrar deneyin."],
];

export function translateApiMessage(message: string): string | null {
  const trimmed = message.trim();
  if (EXACT[trimmed]) return EXACT[trimmed];
  for (const [prefix, translation] of PREFIXES) {
    if (trimmed.startsWith(prefix)) return translation;
  }
  return null;
}
